$runTime    = Get-Date
$actionsTaken = @()
$findings   = @()

# ── 1. SCAN USB DEVICES ───────────────────────────────────────────────────────
Write-Section "Scanning USB & HID Devices"
$allUSB = Get-AllUSBDevices
$totalUSB   = $allUSB.Count
$workingUSB = @($allUSB | Where-Object { $_.ConfigManagerErrorCode -eq 0 }).Count
$usbErrors  = @($allUSB | Where-Object { $_.ConfigManagerErrorCode -ne 0 -and $_.ConfigManagerErrorCode -ne $null })

Write-Host ("  Total USB/HID devices  : {0}" -f $totalUSB) -ForegroundColor White
Write-Host ("  Working (ErrorCode=0)  : {0}" -f $workingUSB) -ForegroundColor Green
Write-Host ("  Error   (ErrorCode≠0)  : {0}" -f $usbErrors.Count) -ForegroundColor $(if ($usbErrors.Count -gt 0) { "Red" } else { "Green" })
Write-Host ("  Health Ratio Formula   : {0} / {1} × 100 = {2}%" -f $workingUSB, $totalUSB, (Compute-HealthRatio $workingUSB $totalUSB)) -ForegroundColor DarkCyan

if ($usbErrors.Count -gt 0) {
    Write-Host ""
    Write-Host "  ⚠ Devices with errors:" -ForegroundColor Red
    foreach ($d in $usbErrors) {
        $msg = "    • [{0}] {1} (ErrorCode: {2})" -f $d.PNPClass, $d.Name, $d.ConfigManagerErrorCode
        Write-Host $msg -ForegroundColor Red
        $findings += $msg.Trim()
    }
}

# ── 2. DETECT STREAMDECK ──────────────────────────────────────────────────────
Write-Section "StreamDeck Detection"
$sdDevices = @($allUSB | Where-Object { Test-IsStreamDeck $_ })
$sdProcess = Get-Process | Where-Object { $_.ProcessName -match 'streamdeck|elgato' } -ErrorAction SilentlyContinue
$sdSoftwareRunning = $sdProcess.Count -gt 0
$sdMissing = 0

if ($sdDevices.Count -gt 0) {
    Write-Host "  ✓ StreamDeck hardware FOUND:" -ForegroundColor Green
    foreach ($sd in $sdDevices) {
        Write-Host ("    • {0}  [{1}]  Status: {2}" -f $sd.Name, $sd.DeviceID, $sd.Status) -ForegroundColor Green
    }
    $findings += "StreamDeck hardware detected: $($sdDevices.Count) device(s)"
} else {
    Write-Host "  ✗ StreamDeck hardware NOT detected in USB/HID scan." -ForegroundColor Red
    $sdMissing = 1
    $findings += "StreamDeck hardware NOT found"

    # Auto-fix attempt 1: pnputil rescan
    Write-Host ""
    Write-Host "  → Attempting USB re-enumeration via pnputil..." -ForegroundColor Yellow
    $r1 = Reset-USBDevice ""
    $actionsTaken += "USB re-enumeration: $r1"
    Start-Sleep -Seconds 3

    # Re-check after rescan
    $allUSB2  = Get-AllUSBDevices
    $sdCheck2 = @($allUSB2 | Where-Object { Test-IsStreamDeck $_ })
    if ($sdCheck2.Count -gt 0) {
        Write-Host "  ✓ StreamDeck found after re-enumeration!" -ForegroundColor Green
        $sdMissing = 0
        $findings += "StreamDeck found after pnputil re-enumeration"
        $actionsTaken += "StreamDeck recovered by USB re-enumeration"
    } else {
        Write-Host "  ✗ StreamDeck still not found after re-enumeration." -ForegroundColor Red
        $findings += "StreamDeck still absent after re-enumeration"
    }
}

Write-Host ""
Write-Host ("  StreamDeck software running: {0}" -f $(if ($sdSoftwareRunning) { "YES ✓" } else { "NO ✗" })) `
    -ForegroundColor $(if ($sdSoftwareRunning) { "Green" } else { "Red" })

# Auto-fix attempt 2: restart software if hardware present but software dead
if ($sdMissing -eq 0 -and -not $sdSoftwareRunning) {
    Write-Host ""
    Write-Host "  → Hardware OK but software not running. Launching StreamDeck..." -ForegroundColor Yellow
    $r2 = Restart-StreamDeckSoftware
    $actionsTaken += "StreamDeck software: $r2"
} elseif ($sdMissing -eq 0 -and $sdSoftwareRunning) {
    Write-Host "  → Software already running — no action needed." -ForegroundColor DarkGray
} elseif ($sdMissing -eq 1) {
    # Hardware not found — restart software in case it recovers on reconnect
    $r3 = Restart-StreamDeckSoftware
    $actionsTaken += "StreamDeck software restart attempt: $r3"
}

# ── 3. PROBLEM DEVICES SUMMARY ────────────────────────────────────────────────
Write-Section "All Problem Devices (System-wide)"
$allProblems = Get-ProblemDevices
if ($allProblems.Count -eq 0) {
    Write-Host "  ✓ No problem devices found." -ForegroundColor Green
} else {
    Write-Host ("  ⚠ {0} device(s) with errors:" -f $allProblems.Count) -ForegroundColor Red
    foreach ($d in ($allProblems | Select-Object -First 20)) {
        Write-Host ("    • [{0}] {1} — ErrorCode {2}" -f $d.PNPClass, $d.Name, $d.ConfigManagerErrorCode) -ForegroundColor Red
    }
}

# ── 4. HEALTH SCORE ───────────────────────────────────────────────────────────
Write-Section "Health Score Calculation"
$healthScore = Compute-HealthScore $allProblems.Count $sdMissing $usbErrors.Count
$healthRatio = Compute-HealthRatio $workingUSB $totalUSB
$stability   = Compute-StabilityIndex $JsonLog

$scoreColor = if ($healthScore -ge 80) { "Green" } elseif ($healthScore -ge 50) { "Yellow" } else { "Red" }

Write-Host ""
Write-Host "  FORMULA:" -ForegroundColor DarkCyan
