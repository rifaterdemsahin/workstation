Write-Host ("             = 100 - ({0}×10) - ({1}×30) - ({2}×5)" -f $allProblems.Count, $sdMissing, $usbErrors.Count) -ForegroundColor DarkGray
Write-Host ("             = {0}" -f $healthScore) -ForegroundColor $scoreColor
Write-Host ""
Write-Host ("  USB Health Ratio : {0}%  ({1}/{2} devices OK)" -f $healthRatio, $workingUSB, $totalUSB) -ForegroundColor White
Write-Host ("  Health Score     : {0}/100" -f $healthScore) -ForegroundColor $scoreColor
Write-Host ("  Stability Index  : {0}" -f $stability) -ForegroundColor DarkCyan
Write-Host ("  Actions Taken    : {0}" -f $(if ($actionsTaken.Count -eq 0) { "None" } else { $actionsTaken.Count })) -ForegroundColor White

# ── 5. WRITE REPORT ───────────────────────────────────────────────────────────
