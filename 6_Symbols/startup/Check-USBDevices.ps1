# Returns all USB + HID devices via CIM (fast, no implicit remoting)
function Get-AllUSBDevices {
    $usb = Get-CimInstance -ClassName Win32_PnPEntity -Filter "PNPClass='USB' OR PNPClass='HIDClass' OR PNPClass='USBDevice'" -ErrorAction SilentlyContinue
    if (-not $usb) {
        $usb = Get-CimInstance -ClassName Win32_PnPEntity | Where-Object {
            $_.DeviceID -match '^USB\\' -or $_.DeviceID -match '^HID\\'
        }
    }
    return $usb
}

# Returns devices with non-zero error codes (WQL-filtered, no full scan)
function Get-ProblemDevices {
    Get-CimInstance -ClassName Win32_PnPEntity -Filter "ConfigManagerErrorCode <> 0" -ErrorAction SilentlyContinue
}

# Matches a device against StreamDeck patterns
function Test-IsStreamDeck($device) {
    foreach ($pat in $StreamDeckPatterns) {
        if ($device.Name -match $pat -or $device.DeviceID -match $pat -or
            $device.Description -match $pat -or $device.Manufacturer -match $pat) {
            return $true
        }
    }
    return $false
}

# Attempt to restart the StreamDeck process
function Restart-StreamDeckSoftware {
    $sdProcess = Get-Process | Where-Object { $_.ProcessName -match 'streamdeck|elgato' } -ErrorAction SilentlyContinue
    if ($sdProcess) {
        Write-Host "  ⚡ Restarting StreamDeck software..." -ForegroundColor Yellow
        $exePath = $sdProcess | Select-Object -First 1 | ForEach-Object { $_.Path }
        $sdProcess | ForEach-Object {
            try { $_ | Stop-Process -Force -ErrorAction SilentlyContinue } catch {}
        }
        Start-Sleep -Seconds 2
        if ($exePath -and (Test-Path $exePath)) {
            Start-Process $exePath
            Write-Host "  ✓ StreamDeck relaunched: $exePath" -ForegroundColor Green
            return "Restarted: $exePath"
        } else {
            Write-Host "  ⚠ Could not find StreamDeck exe to relaunch." -ForegroundColor DarkYellow
            return "Stopped (exe not found)"
        }
    } else {
        # Try common install paths
        $commonPaths = @(
            "$env:ProgramFiles\Elgato\StreamDeck\StreamDeck.exe",
            "${env:ProgramFiles(x86)}\Elgato\StreamDeck\StreamDeck.exe",
            "$env:LOCALAPPDATA\Programs\Elgato\StreamDeck\StreamDeck.exe"
        )
        foreach ($p in $commonPaths) {
            if (Test-Path $p) {
                Start-Process $p
                Write-Host "  ✓ StreamDeck launched from: $p" -ForegroundColor Green
                return "Launched: $p"
            }
        }
        Write-Host "  ✗ StreamDeck software not found in common locations." -ForegroundColor Red
        return "Not found"
    }
}

# Disable + re-enable a USB device via devcon or pnputil workaround
function Reset-USBDevice($deviceId) {
    # We use pnputil to scan for device changes (safe, no devcon needed)
    try {
        $null = pnputil /scan-devices 2>&1
        Write-Host "  ✓ pnputil /scan-devices triggered (USB re-enumeration)" -ForegroundColor Green
        return "pnputil scan triggered"
    } catch {
        return "pnputil failed: $_"
    }
}

# ─────────────────────────────────────────────────────────────────────────────
# FORMULAS / METRICS
# ─────────────────────────────────────────────────────────────────────────────
<#
  HEALTH SCORE FORMULA
  ─────────────────────
  HealthScore (0-100) = 100
      - (ProblemDeviceCount  × 10)   [each broken device  = -10 pts]
      - (StreamDeckMissing   × 30)   [StreamDeck not found = -30 pts]
      - (USBErrorCount       × 5 )   [each USB error code  =  -5 pts]

  USB DEVICE RATIO
  ────────────────
  HealthRatio = WorkingDevices / TotalUSBDevices  (percentage)

  STABILITY INDEX
  ────────────────
  Over the rolling log window:
  StabilityIndex = (RunsWithScore100 / TotalRuns) × 100
#>
function Compute-HealthScore($problemCount, $sdMissing, $usbErrorCount) {
    $score = 100
    $score -= ($problemCount  * 10)
    $score -= ($sdMissing     * 30)
    $score -= ($usbErrorCount *  5)
    return [Math]::Max(0, $score)
}

function Compute-HealthRatio($working, $total) {
    if ($total -eq 0) { return 0 }
    return [Math]::Round(($working / $total) * 100, 1)
}

function Compute-StabilityIndex($jsonLogPath) {
    if (-not (Test-Path $jsonLogPath)) { return "N/A (no history)" }
    try {
        $entries = Get-Content $jsonLogPath -Raw | ConvertFrom-Json
        $cutoff  = (Get-Date).AddDays(-$MaxLogDays)
        $recent  = @($entries | Where-Object { [datetime]$_.Timestamp -gt $cutoff })
        if ($recent.Count -eq 0) { return "N/A (no recent runs)" }
        $perfect = @($recent | Where-Object { $_.HealthScore -eq 100 }).Count
        $index   = [Math]::Round(($perfect / $recent.Count) * 100, 1)
        return "$index% over last $($recent.Count) runs (window: ${MaxLogDays}d)"
    } catch {
        return "N/A (parse error)"
    }
}

